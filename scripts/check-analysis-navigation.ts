import { Compartment, EditorState, Extension } from "@codemirror/state";
import { EditorView } from "@codemirror/view";
import { App, MarkdownView, type Command } from "obsidian";
import FinitionPlugin from "../main";
import { DEFAULT_SETTINGS, FinitionMode, Highlight } from "../plugin/types";
import { resourceFixture } from "./check-linguistic-resources";
import { countDocument, formatDocumentCount } from "../plugin/ui/document-count";

export async function checkAnalysisNavigation(menuOpened: () => number, getMenu: () => Array<{ title: string; click: () => unknown }>): Promise<void> {
	const check = (condition: unknown, message: string) => { if (!condition) throw new Error(message); };
	for (const [number, expected] of [[999, "999 mots"], [1000, "1000 mots"], [1001, "1K mots"], [1050, "1,1K mots"], [10000, "10K mots"], [10500, "10,5K mots"]] as const) check(formatDocumentCount(number, "mot") === expected, `Compteur compact incorrect : ${number}`);
	check(formatDocumentCount(0, "mot") === "0 mots" && formatDocumentCount(1, "mot") === "1 mot" && formatDocumentCount(1, "signe") === "1 signe", "Unité du compteur incorrecte");
	check(countDocument("Bonjour l’été 2026.").words === 3 && countDocument("Un été 😀.").characters === 9 && countDocument("").words === 0, "Comptage du document incorrect");
	const turn = () => new Promise<void>((resolve) => window.setTimeout(resolve, 0));
	const waitFor = async (condition: () => boolean, message: string) => {
		for (let attempt = 0; attempt < 20; attempt++) {
			if (condition()) return;
			await turn();
		}
		throw new Error(message);
	};
	const fixture = await resourceFixture();
	let dictionaryReads = 0;
	const adapter = { ...fixture.adapter, async readBinary(path: string) {
		if (/\/(?:finition-dictionnaire|[a-f0-9]{64})\.json$/.test(path)) dictionaryReads++;
		return fixture.adapter.readBinary(path);
	} };
	const plugin = new FinitionPlugin({} as App, { id: "finition", name: "Finition", version: "0.0.0", minAppVersion: "1.0.0", description: "", author: "", dir: "navigation-test" });
	const host = plugin as unknown as { saved: unknown; commands: Command[]; extensions: Extension[]; cleanup: Array<() => void> };
	host.saved = { ...DEFAULT_SETTINGS, mode: "none", debounceMs: 0, resourcePacks: fixture.revisions };
	let active: MarkdownView | null = null;
	const events = new Map<string, () => void>();
	plugin.app = { vault: { adapter }, workspace: {
		getActiveViewOfType: () => active,
		iterateAllLeaves: (visit: (leaf: { view: MarkdownView }) => void) => { if (active) visit({ view: active }); },
		on: (event: string, callback: () => void) => { events.set(event, callback); return {}; },
	} } as unknown as App;
	await plugin.onload();
	const started = performance.now();
	let frames = 0, lastFrame = started, maxFrameGap = 0, loading = true;
	const tick = (now: number) => {
		frames++;
		maxFrameGap = Math.max(maxFrameGap, now - lastFrame);
		lastFrame = now;
		if (loading) requestAnimationFrame(tick);
	};
	requestAnimationFrame(tick);
	await Promise.all([plugin.loadLexiconData(true), plugin.loadLexiconData(true)]);
	await new Promise(requestAnimationFrame);
	loading = false;
	check(dictionaryReads === 1 && plugin.lexicon.get("serrait") === "serrer" && plugin.lexicon.get("abaissant") === "abaisser", "Chargement partagé du lexique ou préférences de lemmes perdus");
	check(frames > 0, "Le chargement du lexique bloque l’affichage");
	const loadedLexicon = plugin.lexicon;
	await plugin.loadLexiconData(true);
	check(plugin.lexicon === loadedLexicon && dictionaryReads === 1, "Le changement de mode recharge le lexique");
	console.error("finition-test-step", `lexique : ${Math.round(performance.now() - started)} ms, ${frames} images, pause maximale ${Math.round(maxFrameGap)} ms, une seule lecture`);
	check(getComputedStyle(document.querySelector(".finition-status-bar-item")!).opacity === "1", "Barre d’état Finition atténuée sans mode actif");
	check(!plugin.settings.hideBacklinksCount && !document.body.classList.contains("finition-hide-backlinks-count"), "Compteur de backlinks masqué par défaut");
	plugin.settings.hideBacklinksCount = true;
	await plugin.saveSettings();
	await plugin.loadSettings();
	check(plugin.settings.hideBacklinksCount && document.body.classList.contains("finition-hide-backlinks-count"), "Masquage des backlinks non persisté ou non appliqué");
	plugin.settings.hideBacklinksCount = false;
	await plugin.saveSettings();
	check(!document.body.classList.contains("finition-hide-backlinks-count"), "Masquage des backlinks encore actif après désactivation");
	const parent = document.body.createDiv();
	const text = "Introduction.\n\nIl semblerait que tout change. Il semblerait que rien ne bouge.";
	const layout = new Compartment();
	const view = new EditorView({ parent, state: EditorState.create({ doc: text, extensions: [...host.extensions, layout.of([])] }) });
	active = Object.assign(Object.create(MarkdownView.prototype) as MarkdownView, { editor: { cm: view, getValue: () => view.state.doc.toString() } });
	const documentCount = document.querySelector<HTMLElement>(".finition-document-count");
	check(!documentCount!.parentElement!.hasAttribute("aria-label"), "L’infobulle Finition recouvre celle du compteur");
	check(documentCount?.hidden, "Compteur du document visible par défaut");
	check(documentCount!.parentElement!.firstElementChild === documentCount, "Compteur du document placé après la note de musique");
	check(documentCount!.nextElementSibling?.getAttribute("aria-label") === "Finition", "Infobulle Finition absente de l’icône");
	plugin.settings.documentCountDisplay = "both";
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: "Un été 😀." } });
	events.get("editor-change")!();
	check(!documentCount!.hidden && documentCount!.textContent === "2 mots · 9 signes", "Compteurs non actualisés à la frappe");
	check(documentCount!.title === "2 mots · 9 signes (espaces compris)", "Infobulle sans les deux décomptes exacts");
	plugin.settings.documentCountDisplay = "characters";
	await plugin.saveSettings();
	await plugin.loadSettings();
	plugin.updateDocumentCounts();
	check(plugin.settings.documentCountDisplay === "characters" && documentCount!.textContent === "9 signes", "Option signes non persistée");
	check(documentCount!.title === "2 mots · 9 signes (espaces compris)", "Infobulle incomplète avec les signes seuls");
	plugin.settings.documentCountDisplay = "words";
	plugin.updateDocumentCounts();
	check(documentCount!.textContent === "2 mots", "Option mots incorrecte");
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: "mot ".repeat(1051) } });
	events.get("editor-change")!();
	check(documentCount!.textContent === "1,1K mots" && documentCount!.title === "1\u202f051 mots · 4\u202f204 signes (espaces compris)", "Infobulle arrondie ou incomplète avec les mots seuls");
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: "a" } });
	events.get("editor-change")!();
	check(documentCount!.title === "1 mot · 1 signe (espaces compris)", "Infobulle incorrecte au singulier");
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: "Un été 😀." } });
	events.get("editor-change")!();
	active = null;
	events.get("file-open")!();
	check(documentCount!.hidden, "Compteur visible sans document");
	active = Object.assign(Object.create(MarkdownView.prototype) as MarkdownView, { editor: { cm: view, getValue: () => view.state.doc.toString() } });
	events.get("active-leaf-change")!();
	check(!documentCount!.hidden && documentCount!.textContent === "2 mots", "Compteur absent après changement de note");
	plugin.settings.documentCountDisplay = "none";
	plugin.updateDocumentCounts();
	check(documentCount!.hidden, "Compteur encore visible après désactivation");
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: text } });
	const counter = document.querySelector<HTMLElement>(".finition-analysis-count");
	const next = document.querySelector<HTMLButtonElement>(".finition-next-occurrence");
	check(counter && next, "Compteur et flèche absents");
	const activate = async (mode: FinitionMode, expected: number, first: number) => {
		document.querySelector<HTMLElement>("#result")!.dataset.stage = mode;
		view.dispatch({ selection: { anchor: view.state.doc.length, head: view.state.doc.length - 1 } });
		const selection = view.state.selection.main;
		const scrollTop = view.scrollDOM.scrollTop;
		await plugin.setMode(mode);
		document.querySelector<HTMLElement>("#result")!.dataset.stage = `${mode}: mode activé`;
		await waitFor(() => counter!.textContent === String(expected), `Activation ${mode} : compteur incorrect`);
		await turn();
		check(view.state.selection.main.eq(selection) && view.scrollDOM.scrollTop === scrollTop, `Activation ${mode} : sélection ou défilement déplacé`);
		next!.click();
		check(view.state.selection.main.head === first && view.hasFocus, `Navigation ${mode} : première occurrence inaccessible`);
	};
	const initialLimit = plugin.settings.maxDocumentLength;
	const prefix = "😀 Le chat et le chat, mais pas la souris.";
	const longText = prefix + " Le chat et le chat.";
	for (const [mode, expandedCount, first, selector] of [
		["hinges", 3, prefix.indexOf("et"), ".finition-hinge"],
		["repetition", 4, prefix.indexOf("chat"), ".finition-repeat"],
	] as const) {
		plugin.settings.maxDocumentLength = prefix.length;
		await plugin.saveSettings();
		view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: longText } });
		await activate(mode, 2, first);
		const marks = Array.from(view.dom.querySelectorAll<HTMLElement>(selector));
		check(marks.length === 2 && marks.every(mark => view.posAtDOM(mark) + mark.textContent.length <= prefix.length), `${mode} : surlignage absent du début ou présent au-delà de la limite`);
		next!.click();
		next!.click();
		check(view.state.selection.main.head === first, `${mode} : navigation au-delà du début analysé`);
		plugin.settings.maxDocumentLength = longText.length;
		await plugin.saveSettings();
		plugin.refreshAllEditors();
		await waitFor(() => counter!.textContent === String(expandedCount), `${mode} : agrandir la limite ne restaure pas les surlignages`);
		plugin.settings.maxDocumentLength = prefix.length;
		await plugin.saveSettings();
		const inserted = "Un mot. ";
		view.dispatch({ changes: { from: 0, insert: inserted } });
		await waitFor(() => counter!.textContent === "2", `${mode} : compteur périmé après modification du début`);
		check(view.posAtDOM(view.dom.querySelector<HTMLElement>(selector)!) === first + inserted.length, `${mode} : positions UTF-16 décalées après modification`);
		check(view.state.doc.toString() === inserted + longText, `${mode} : le texte hors limite a été modifié`);
	}
	const boundaryText = "Le chat et la niche, mais loin.";
	plugin.settings.maxDocumentLength = boundaryText.indexOf("niche") + 2;
	await plugin.saveSettings();
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: boundaryText } });
	await activate("hinges", 1, boundaryText.indexOf("et"));
	check(view.dom.querySelector(".finition-hinge")!.textContent === "et", "Un mot tronqué à la limite devient une fausse charnière");
	plugin.settings.maxDocumentLength = initialLimit;
	await plugin.saveSettings();
	const filler = "\nUne phrase sans lien.";
	const oversized = (prefix + filler.repeat(Math.ceil(initialLimit / filler.length))).slice(0, initialLimit) + " et";
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: oversized } });
	await waitFor(() => counter!.textContent === "2", "Le début d’un document dépassant la limite par défaut n’est pas analysé");
	check(view.dom.querySelector(".finition-hinge")?.textContent === "et" && view.state.doc.toString() === oversized, "Le surlignage d’un grand document altère ou masque son début");
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: text } });
	console.error("finition-test-step", "longs documents : début surligné, navigation bornée, limite réglable et positions UTF-16 vérifiés");
	const scrollText = text + "\nUn paragraphe de plus.".repeat(100);
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: scrollText }, selection: { anchor: scrollText.length },
		effects: layout.reconfigure(EditorView.theme({ ".cm-scroller": { height: "180px", overflow: "auto" } })),
	});
	await new Promise(requestAnimationFrame);
	view.scrollDOM.scrollTop = view.scrollDOM.scrollHeight;
	await new Promise(requestAnimationFrame);
	check(view.scrollDOM.scrollTop > 0, "Le scénario de lecture ne défile pas réellement");
	await activate("hedging", 2, text.indexOf("Il semblerait"));
	await plugin.setMode("hedging");
	view.dispatch({ effects: layout.reconfigure([]) });
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: text } });
	await activate("hedging", 2, text.indexOf("Il semblerait"));
	const highlight = view.dom.querySelector<HTMLElement>(".finition-hedging")!;
	const normalBackground = getComputedStyle(highlight).backgroundColor;
	highlight.click();
	const focused = view.dom.querySelector<HTMLElement>(".finition-focused")!;
	check(focused && getComputedStyle(focused).backgroundColor === "rgb(0, 0, 0)" && getComputedStyle(focused).color === "rgb(255, 255, 255)", "Le groupe sélectionné ne reste pas blanc sur noir");
	focused.click();
	check(!view.dom.querySelector(".finition-focused") && getComputedStyle(view.dom.querySelector<HTMLElement>(".finition-hedging")!).backgroundColor === normalBackground, "La désélection ne restaure pas la couleur du groupe");
	next!.click();
	check(view.state.selection.main.head === text.lastIndexOf("Il semblerait"), "La flèche ne rejoint pas l’occurrence suivante");
	next!.click();
	check(view.state.selection.main.head === text.indexOf("Il semblerait"), "La flèche ne boucle pas vers la première occurrence");
	check(menuOpened() === 0, "La flèche ouvre aussi le menu des modes");
	check(view.state.doc.toString() === text, "La navigation a modifié le texte");
	view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: "Un texte sans locution." } });
	await waitFor(() => counter!.textContent === "0" && next!.disabled, "Le compteur reste périmé après modification");
	const replace = (text: string) => view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: text } });
	const stereotype = "Préambule. Il serrait les poings. Elle serrait les poings.";
	replace(stereotype);
	await activate("stereotype", 2, stereotype.indexOf("serrait"));
	replace("Le chat dort. Le chien court. Le vent souffle.");
	await activate("burstiness", 3, 0);
	const ternary = "Introduction.\n\nUn rire sec, maigre, tordu.";
	for (const [word, category] of Object.entries({ introduction: "nom", un: "déterminant", rire: "nom|verbe", sec: "adjectif|nom", maigre: "adjectif|nom", tordu: "participe|adjectif" })) plugin.wordCategoryCache.set(word, category);
	replace(ternary);
	await activate("ternary", 1, ternary.indexOf("Un rire"));
	await plugin.setMode("ternary");
	await waitFor(() => counter!.hidden && next!.hidden, "Les contrôles restent visibles quand le mode est désactivé");
	check(getComputedStyle(counter!).display === "none" && getComputedStyle(next!).display === "none", "Les contrôles masqués occupent encore la barre d’état");
	await plugin.setMode("hedging");
	await waitFor(() => counter!.textContent === "0", "Le mode vide ne revient pas à zéro");
	const internal = plugin as unknown as {
		updateAnalysisHighlights: (view: EditorView, highlights: Highlight[], pending: boolean) => void;
	};
	const ranges = [{ from: 2, to: 4, lemma: "fixture", colorIndex: 0 }];
	view.dispatch({ selection: { anchor: view.state.doc.length } });
	internal.updateAnalysisHighlights(view, ranges, true);
	await turn();
	check(counter!.textContent === "…" && next!.disabled && view.state.selection.main.head === view.state.doc.length, "Un résultat provisoire déclenche la navigation");
	internal.updateAnalysisHighlights(view, ranges, false);
	await turn();
	check(counter!.textContent === "1" && view.state.selection.main.head === view.state.doc.length, "La résolution asynchrone déplace le curseur");
	next!.click();
	check(view.state.selection.main.head === 2, "La flèche ne rejoint pas le résultat asynchrone");
	const other = new EditorView({ parent: document.body.createDiv(), state: EditorState.create({ doc: "Autre note." }) });
	view.dispatch({ selection: { anchor: view.state.doc.length } });
	active = Object.assign(Object.create(MarkdownView.prototype) as MarkdownView, { editor: { cm: other } });
	internal.updateAnalysisHighlights(view, ranges, false);
	plugin.updateStatusBarIcon();
	await turn();
	check(view.state.selection.main.head === view.state.doc.length, "Une navigation différée déplace le curseur d’une note inactive");
	check(counter!.textContent !== "1", "Une note inactive écrase le compteur actif");
	active = Object.assign(Object.create(MarkdownView.prototype) as MarkdownView, { editor: { cm: view } });
	await plugin.setMode("hedging");
	const showMenu = () => {
		(plugin as unknown as { showModeMenu: (event: MouseEvent) => void }).showModeMenu(new MouseEvent("click"));
		return getMenu();
	};
	check(!showMenu().some(item => item.title === "Reset"), "Reset visible sans fonction active");
	await plugin.setMode("hinges");
	const resetPosition = view.state.selection.main.head;
	const resetText = view.state.doc.toString();
	const resetMenu = showMenu();
	check(resetMenu.at(-1)?.title === "Reset", "Reset absent du bas du menu actif");
	const resetCommand = host.commands.find(command => command.name === "Reset");
	check(resetCommand?.checkCallback?.(true), "Reset absent de la palette pour une fonction active");
	await resetMenu.at(-1)!.click();
	await waitFor(() => plugin.settings.mode === "none" && counter!.hidden && next!.hidden, "Reset laisse les surlignages actifs");
	check(view.state.selection.main.head === resetPosition && view.state.doc.toString() === resetText, "Reset déplace le curseur ou modifie le texte");
	check(!showMenu().some(item => item.title === "Reset") && resetCommand!.checkCallback!(true) === false, "Reset reste disponible après annulation");
	const misspelled = "Une fote. Une autre fote.";
	replace(misspelled);
	const firstError = misspelled.indexOf("fote"), lastError = misspelled.lastIndexOf("fote");
	plugin.grammalecteErrors = [firstError, lastError].map(nStart => ({ nStart, nEnd: nStart + 4, sType: "orthographe", sMessage: "Orthographe", sRuleId: "test", aSuggestions: ["faute"], sValue: "fote" }));
	plugin.grammalecteErrorsVersion++;
	const spellingPosition = view.state.selection.main.head;
	plugin.refreshAllEditors();
	await waitFor(() => counter!.textContent === "2" && !next!.hidden && !next!.disabled, "Grammalecte : compteur et flèche absents");
	check(view.state.selection.main.head === spellingPosition, "L’affichage des corrections déplace le curseur");
	check(showMenu().at(-1)?.title === "Reset", "Reset absent pour les corrections seules");
	check(next!.getAttribute("aria-label") === "Faute suivante", "Grammalecte : flèche sans libellé adapté");
	const menuBeforeSpellingNavigation = menuOpened();
	view.dispatch({ selection: { anchor: 0 } });
	next!.click();
	check(view.state.selection.main.head === firstError && view.hasFocus, "Grammalecte : première faute inaccessible");
	next!.click();
	check(view.state.selection.main.head === lastError, "Grammalecte : faute suivante inaccessible");
	next!.click();
	check(view.state.selection.main.head === firstError, "Grammalecte : retour à la première faute absent");
	check(menuOpened() === menuBeforeSpellingNavigation && view.state.doc.toString() === misspelled, "Grammalecte : navigation modifie le texte ou ouvre le menu");
	active = Object.assign(Object.create(MarkdownView.prototype) as MarkdownView, { editor: { cm: other } });
	plugin.updateStatusBarIcon();
	check(next!.hidden, "Grammalecte : navigation proposée dans une note non analysée");
	active = Object.assign(Object.create(MarkdownView.prototype) as MarkdownView, { editor: { cm: view } });
	plugin.updateStatusBarIcon();
	check(!next!.hidden && counter!.textContent === "2", "Grammalecte : navigation perdue au retour dans la note");
	const error = view.dom.querySelector<HTMLElement>(".finition-grammalecte-spelling")!;
	const underline = getComputedStyle(error);
	check(underline.borderBottomStyle === "dotted" && underline.borderBottomWidth === "2px" && underline.borderBottomColor === "rgb(224, 82, 82)", "Grammalecte : soulignement orthographique absent");
	error.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, button: 0 }));
	document.querySelector<HTMLButtonElement>(".finition-grammalecte-popup-suggestions button")!.click();
	check(view.state.doc.toString() === "Une faute. Une autre fote.", "Grammalecte : correction non appliquée");
	await waitFor(() => counter!.textContent === "1", "Grammalecte : compteur périmé après correction");
	next!.click();
	check(view.state.selection.main.head === view.state.doc.toString().indexOf("fote"), "Grammalecte : positions périmées après correction");
	view.dom.querySelector<HTMLElement>(".finition-grammalecte-spelling")!.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, button: 0 }));
	document.querySelector<HTMLButtonElement>(".finition-grammalecte-popup-ignore")!.click();
	await waitFor(() => next!.hidden || next!.disabled, "Grammalecte : navigation toujours active sans faute");
	check(!view.dom.querySelector(".finition-grammalecte-spelling"), "Grammalecte : faute ignorée toujours soulignée");
	active = null;
	plugin.updateStatusBarIcon();
	check(counter!.hidden && next!.hidden, "Les contrôles restent visibles sans éditeur");
	const command = (name: string) => {
		const found = host.commands.find(command => command.name === name);
		check(found, `Commande absente : ${name}`);
		return found!;
	};
	check(new Set(host.commands.map(command => command.id)).size === host.commands.length, "Identifiants de commande dupliqués");
	for (const debug of [false, true]) {
		plugin.settings.debugMode = debug;
		(plugin as unknown as { showModeMenu: (event: MouseEvent) => void }).showModeMenu(new MouseEvent("click"));
		for (const item of getMenu()) command(item.title);
		check(command("Structure").checkCallback!(true) === debug, "Structure ne respecte pas le mode debug dans la palette");
	}
	for (const [name, mode] of [["Répétitions", "repetition"], ["Atténuations", "hedging"], ["Stéréotypes", "stereotype"], ["Monotonie", "burstiness"], ["Tricolons", "ternary"], ["Cadence", "cadence"], ["Charnières", "hinges"]] as const) {
		plugin.settings.mode = "none";
		const action = command(name).checkCallback!;
		check(action(true) === true && plugin.settings.mode === "none", `${name} : vérifier active le mode`);
		action(false);
		await waitFor(() => plugin.settings.mode === mode, `${name} : commande sans effet`);
		action(false);
		await waitFor(() => plugin.settings.mode === "none", `${name} : commande sans bascule`);
	}
	for (const [name, engine] of [["Grammalecte", "grammalecte"], ["Neuronal", "finition-corrector"]] as const) {
		plugin.settings.spellingEngine = engine;
		plugin.grammalecteErrors = [{ nStart: 0, nEnd: 4, sRuleId: "test", sType: "orthographe", sMessage: "Faute", aSuggestions: [] }];
		check(command(name).checkCallback!(true) === true && plugin.grammalecteErrors.length === 1, `${name} : vérifier efface les suggestions`);
		command(name).checkCallback!(false);
		check(plugin.grammalecteErrors.length === 0, `${name} : la commande ne désactive pas les corrections`);
	}
	plugin.settings.hideBacklinksCount = true;
	await plugin.saveSettings();
	plugin.onunload();
	check(!document.body.classList.contains("finition-hide-backlinks-count"), "Masquage des backlinks conservé après déchargement");
	for (const cleanup of host.cleanup) cleanup();
	view.destroy();
	other.destroy();
}
